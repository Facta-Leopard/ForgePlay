  const message = (locale, key) => {
    return localeData[locale]?.[key] ?? localeData.en[key] ?? "";
  };

  const updateLocaleLinks = (locale) => {
    document.querySelectorAll("[data-locale-link]").forEach((link) => {
      const original = link.dataset.localeHref || link.getAttribute("href");
      if (!original || original.startsWith("#")) return;
      link.dataset.localeHref = original;
      const [pathAndQuery, hash = ""] = original.split("#", 2);
      const [path] = pathAndQuery.split("?", 1);
      link.setAttribute("href", `${path}?lang=${encodeURIComponent(locale)}${hash ? `#${hash}` : ""}`);
    });
  };

  const updateLanguageSections = (locale) => {
    document.querySelectorAll(".language-section[lang]").forEach((section) => {
      section.hidden = section.getAttribute("lang") !== locale;
    });
  };

  const updateDocumentMetadata = (locale) => {
    const page = document.body.dataset.page || "home";
    const title = message(locale, `${page}.metaTitle`);
    const description = message(locale, `${page}.metaDescription`);
    if (title) document.title = title;
    const descriptionMeta = document.querySelector('meta[name="description"]');
    if (descriptionMeta && description) descriptionMeta.setAttribute("content", description);
  };

  const markCurrentPageNavigation = () => {
    const page = document.body.dataset.page || "home";
    const pageFiles = {
      home: "index.html",
      compatibility: "compatibility.html",
      updates: "updates.html",
      why: "why.html",
      license: "license.html",
      privacy: "privacy.html",
      support: "support.html"
    };
    const currentFile = pageFiles[page];
    document.querySelectorAll(".nav-links a").forEach((link) => {
      link.removeAttribute("aria-current");
      const original = link.dataset.localeHref || link.getAttribute("href");
      if (!original || original.startsWith("#")) return;
      const url = new URL(original, window.location.href);
      const file = url.pathname.split("/").pop() || "index.html";
      if (!url.hash && file === currentFile) {
        link.setAttribute("aria-current", "page");
      }
    });
  };

  const centerCurrentNavigation = (behavior = "auto") => {
    if (!window.matchMedia("(max-width: 760px)").matches) return;
    const navigation = document.querySelector(".nav-links");
    const current = navigation?.querySelector(
      'a[aria-current="page"], a[aria-current="location"]'
    );
    if (!navigation || !current) return;

    const left = current.offsetLeft - ((navigation.clientWidth - current.offsetWidth) / 2);
    const maximum = Math.max(0, navigation.scrollWidth - navigation.clientWidth);
    navigation.scrollTo({
      left: Math.min(maximum, Math.max(0, left)),
      behavior
    });
  };

  const initializeSectionNavigation = () => {
    if ((document.body.dataset.page || "home") !== "home") return;
    const sectionLinks = new Map();
    document.querySelectorAll(".nav-links a").forEach((link) => {
      const original = link.dataset.localeHref || link.getAttribute("href");
      if (!original) return;
      const url = new URL(original, window.location.href);
      const file = url.pathname.split("/").pop() || "index.html";
      if (file === "index.html" && url.hash) {
        sectionLinks.set(url.hash.slice(1), link);
      }
    });

    const setCurrentSection = (sectionID = null) => {
      sectionLinks.forEach((link, id) => {
        if (id === sectionID) {
          link.setAttribute("aria-current", "location");
        } else {
          link.removeAttribute("aria-current");
        }
      });
      centerCurrentNavigation();
    };

    const initialSection = window.location.hash.slice(1);
    if (sectionLinks.has(initialSection)) setCurrentSection(initialSection);
    if (!("IntersectionObserver" in window)) return;

    const observer = new IntersectionObserver((entries) => {
      const visible = entries
        .filter((entry) => entry.isIntersecting)
        .sort((left, right) => right.intersectionRatio - left.intersectionRatio)[0];
      if (visible) {
        setCurrentSection(visible.target.id);
      } else if (!sectionLinks.has(window.location.hash.slice(1))) {
        setCurrentSection();
      }
    }, {
      rootMargin: "-18% 0px -62% 0px",
      threshold: [0, 0.15, 0.35]
    });

    sectionLinks.forEach((_, id) => {
      const section = document.getElementById(id);
      if (section) observer.observe(section);
    });
  };

